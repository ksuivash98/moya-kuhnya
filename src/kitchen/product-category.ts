import { proteinProduct } from "./protein-products";
/** Conservative suggestions within the existing shared category catalogue. */
export function suggestProductCategory(name: string): string {
  const protein = proteinProduct(name);
  if (protein) return protein.category;
  const n = name
    .toLocaleLowerCase("ru")
    .replace(/ё/g, "е")
    .replace(/[()%,–—-]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  const has = (pattern: RegExp) => pattern.test(n);
  if (
    has(
      /(?:^| )(?:сгущенка|сгущенное|сгущеное|сметана|сметаны|сливки|сливок|творог|творога|кефир|кефира|йогурт|йогурта|сыр|сыра|молоко|молока)(?: |$)/,
    ) ||
    has(/(?:^| )(?:сливочное масло|масло сливочное)(?: |$)/)
  )
    return "Молочные продукты";
  if (
    has(
      /(?:^| )(?:колбаса|колбасы|сосиски|сосисок|сардельки|бекон|ветчина|говядина|говядины|свинина|свинины|курица|курицы|куриное|куриный|куриные|куриных|индейка|индейки|фарш)(?: |$)/,
    ) &&
    !has(/(?:^| )(?:бульон|суп|соус|яйцо|яйца|яиц)(?: |$)/)
  )
    return "Мясо";
  if (
    has(
      /(?:^| )(?:консервированная|консервированный|консервированные|консервированного|консервированной)(?: |$)/,
    ) ||
    has(/(?:^| )(?:томатная паста|томатный соус)(?: |$)/)
  )
    return "Консервы";
  if (
    has(
      /(?:^| )(?:лосось|лосося|семга|треска|трески|минтай|минтая|скумбрия|скумбрии|форель|тунец|тунца|горбуша|горбуши|рыба|рыбы)(?: |$)/,
    )
  )
    return "Рыба";
  if (
    has(
      /(?:^| )(?:лук|лука|картофель|картофеля|морковь|моркови|чеснок|чеснока|помидор|помидоры|помидоров|томаты|огурец|огурцы|огурцов|капуста|капусты|кабачок|кабачки|свекла|свеклы)(?: |$)/,
    ) ||
    has(/(?:^| )(?:болгарский перец|перец болгарский|сладкий перец)(?: |$)/)
  )
    return "Овощи";
  if (
    has(
      /(?:^| )(?:лимон|лимоны|лимона|яблоко|яблоки|яблок|груша|груши|банан|бананы|банана|апельсин|апельсины|мандарин|мандарины|лайм|киви)(?: |$)/,
    )
  )
    return "Фрукты";
  if (
    has(
      /(?:^| )(?:рис|риса|гречка|гречки|гречневая крупа|овсяные хлопья|овсянка|пшено|перловка|манная крупа|булгур)(?: |$)/,
    )
  )
    return "Крупы";
  if (
    has(
      /(?:^| )(?:макароны|макарон|спагетти|вермишель|паста|пенне|фузилли|лапша|лапши)(?: |$)/,
    )
  )
    return "Макароны";
  if (
    has(
      /(?:^| )(?:соль|соли|паприка|корица|куркума|лавровый лист|кориандр|ванилин|уксус|уксуса|розмарин|орегано|базилик)(?: |$)/,
    ) ||
    has(
      /(?:^| )(?:черный перец|перец черный|молотый перец|перец молотый|черный молотый перец)(?: |$)/,
    )
  )
    return "Специи";
  if (has(/(?:^| )(?:чай|кофе|вода|воды|сок|сока)(?: |$)/)) return "Напитки";
  if (has(/(?:^| )(?:шоколад|конфеты|печенье|мед|варенье)(?: |$)/))
    return "Сладости";
  return "Другое";
}
