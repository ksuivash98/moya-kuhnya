import { test, expect } from "vitest";
import { suggestProductCategory } from "../src/kitchen/product-category";
test.each([
  ["сметана 25%", "Молочные продукты"],
  ["Сливки 10–20%", "Молочные продукты"],
  ["варёная сгущёнка", "Молочные продукты"],
  ["Сливочное масло для формочек", "Молочные продукты"],
  ["копчёная колбаса", "Мясо"],
  ["Куриные сосиски", "Мясо"],
  ["чеснок свежий", "Овощи"],
  ["Зелёный лук", "Овощи"],
  ["Гречневая крупа (ядрица)", "Крупы"],
  ["Уксус 9%", "Специи"],
  ["томатный соус", "Консервы"],
  ["Яичная лапша (сухая)", "Макароны"],
  ["начинка", "Другое"],
  ["Куриный бульон", "Другое"],
  ["кукурузный крахмал", "Другое"],
])("категория %s → %s", (name, category) =>
  expect(suggestProductCategory(name)).toBe(category),
);
